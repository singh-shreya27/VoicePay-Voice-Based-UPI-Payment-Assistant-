android {
    namespace = "com.example.voicepay"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.example.voicepay"
        minSdk = 24
        targetSdk = 37
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

        // Becomes the constant BuildConfig.BACKEND_URL in Kotlin code (like process.env in Node,
        // but fixed at build time). Not a secret: the API keys stay on the backend.
        buildConfigField("String", "BACKEND_URL", "\"https://voice-assisted-payment-system.onrender.com/\"")
    }

    // The release signing key lives in keystore.properties (git-ignored, see that file).
    // If it's missing (e.g. on a teammate's machine) release builds are simply left unsigned.
    val keystoreFile = rootProject.file("keystore.properties")
    val signing = Properties().apply { if (keystoreFile.exists()) keystoreFile.inputStream().use { load(it) } }

    signingConfigs {
        if (keystoreFile.exists()) {
            create("release") {
                storeFile = rootProject.file(signing.getProperty("storeFile"))
                storePassword = signing.getProperty("storePassword")
                keyAlias = signing.getProperty("keyAlias")
                keyPassword = signing.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("release")
            // R8 shrinks and optimizes release builds (like a JS minifier). It must cover the whole
            // app: limiting it to some packages (the template's `packageScope`) split Kotlin's own
            // classes and crashed the app on launch.
            optimization {
                enable = true
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
}

